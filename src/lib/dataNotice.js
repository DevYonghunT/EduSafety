export function buildTeacherNotice() {
  const lines = [
    '[에듀 세이프] 앱 제출 전 안내 — 데이터 처리 방식',
    '',
    '선생님이 제출하신 앱은 아래 방식으로 심사됩니다. 제출 전에 꼭 읽어 주세요.',
  ]
  for (const p of DATA_NOTICE_POINTS) {
    lines.push('', `■ ${p.title}`, p.body)
  }
  lines.push('', '문의는 심사 담당자에게 해주세요. 제출해 주셔서 감사합니다.')
  return lines.join('\n')
}
